#!/usr/bin/env python3
"""
Build the retrieval caches for "combined" ablations — negatives generated by an
alternative backbone AND retrieval enabled — without re-retrieving the positives.

The positives of the alternative-backbone datasets are byte-identical to the
baseline's, so their candidates are recycled from an existing cache and only the
new negatives are retrieved. Per dataset:

  1. preflight            — read-only checks that the recycling is sound
  2. rekey_retrieval_cache.py   → seeds <dest>/pairwise/retrieval_cache.json with
                                  the positives, re-keyed to the new YAML
  3. retrieve_candidates.py     → fills in the negatives (incremental, resumable)
  4. flatten_retrieval_cache.py → derives <dest>/pointwise/retrieval_cache.json by
                                  idea text; costs no API calls
  5. coverage summary + a ready-to-paste ablations.yaml snippet

SAFETY — this script never overwrites anything it did not create:
  * All output goes under <output_root>/<label>/, a directory the script creates
    and records in .build_manifest.json. A destination that exists without a
    matching manifest aborts the run; so does a manifest whose inputs differ.
  * Sources (datasets, source cache) are opened read-only, and their size+mtime is
    re-verified after every subprocess.
  * Step 2 runs only when its output is absent. Steps 3 and 4 rewrite their own
    prior output by design: retrieve_candidates.py resumes by extending the cache it
    is pointed at (here, always one we seeded), and step 4 is a deterministic
    re-derivation from step 3's result.

Re-running the same command is also the repair pass: step 2 is skipped, and with
`retry_failed_queries` set in the config, step 3 re-retrieves ideas whose queries
failed or came back empty. Step 4 always re-derives, so the pointwise cache cannot
lag behind a repaired pairwise one.

Usage:
    export PYTHONPATH=$PWD/src
    export SECRETS=$PWD/secrets.toml
    python3 scripts/build_combined_retrieval.py --config scripts/build_combined_retrieval.yaml --dry-run  --allow-positive-misses      # plan + cost
    python3 scripts/build_combined_retrieval.py --allow-positive-misses --datasets gpt_5.1_backbone  # one dataset first
    python3 scripts/build_combined_retrieval.py --allow-positive-misses  # the rest
"""

import argparse
import json
import os
import subprocess
import sys
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import yaml

_REPO_ROOT = Path(__file__).resolve().parents[2]
_REKEY = _REPO_ROOT / "scripts" / "rekey_retrieval_cache.py"
_RETRIEVE = _REPO_ROOT / "src" / "novelty_eval" / "retrieval" / "retrieve_candidates.py"
_FLATTEN = _REPO_ROOT / "src" / "novelty_eval" / "retrieval" / "flatten_retrieval_cache.py"

# rekey_retrieval_cache.py matches ideas on the first N characters of the raw text.
# Preflight must use the identical rule to be predictive of what rekey will do.
_SNIPPET_LEN = 100

_MANIFEST_NAME = ".build_manifest.json"


# ── Paths & read-only guards ──────────────────────────────────────────────────

def resolve(p: str) -> Path:
    path = Path(p)
    return path if path.is_absolute() else _REPO_ROOT / path


def rel(p: Path) -> str:
    try:
        return str(p.relative_to(_REPO_ROOT))
    except ValueError:
        return str(p)


class SourceGuard:
    """Records size+mtime of every source file so tampering is caught immediately."""

    def __init__(self, paths: List[Path]):
        self.sig = {p: self._stat(p) for p in paths}

    @staticmethod
    def _stat(p: Path) -> Tuple[int, int]:
        st = p.stat()
        return st.st_size, st.st_mtime_ns

    def verify(self, context: str) -> None:
        for p, before in self.sig.items():
            if not p.exists():
                die(f"source file disappeared during {context}: {rel(p)}")
            if self._stat(p) != before:
                die(f"source file was MODIFIED during {context}: {rel(p)}\n"
                    f"      This should never happen — inspect before continuing.")


def die(msg: str) -> None:
    print(f"\nABORT: {msg}", file=sys.stderr)
    sys.exit(1)


# ── Loading ───────────────────────────────────────────────────────────────────

def load_yaml(path: Path) -> dict:
    with open(path) as f:
        return yaml.safe_load(f) or {}


def build_snippet_index(source_cache: dict) -> Tuple[Dict[str, dict], List[str]]:
    """text[:N] -> cache entry, mirroring rekey_retrieval_cache.build_text_index."""
    index: Dict[str, dict] = {}
    collisions: List[str] = []
    for ideas in source_cache.values():
        for entry in ideas.values():
            key = entry.get("text", "")[:_SNIPPET_LEN]
            if not key:
                continue
            if key in index:
                collisions.append(key)
            index[key] = entry
    return index, collisions


# ── Preflight ─────────────────────────────────────────────────────────────────

def preflight(label: str,
              pairwise_yaml: dict,
              pointwise_yaml: Optional[dict],
              snippet_index: Dict[str, dict],
              collisions: List[str],
              allow_positive_misses: bool) -> dict:
    """Read-only validation. Returns a plan dict; exits on anything unsound."""
    problems: List[str] = []

    n_instances = len(pairwise_yaml)
    positives_matched = 0
    positives_empty = 0          # recycled but with 0 candidates → will be re-retrieved
    positives_missing: List[str] = []
    negatives = 0
    missing_type: List[str] = []
    type_vs_winner_mismatch: List[str] = []

    for pid, data in pairwise_yaml.items():
        ideas = data.get("ideas") or {}
        metadata = data.get("metadata") or {}

        pos_keys = [k for k in ideas if (metadata.get(k) or {}).get("type") == "POSITIVE"]
        for k in ideas:
            itype = (metadata.get(k) or {}).get("type")
            if itype not in ("POSITIVE", "NEGATIVE"):
                missing_type.append(f"{pid}/{k}")
            elif itype == "NEGATIVE":
                negatives += 1

        # rekey keys the seed off metadata.type; the sweep scores off expected_winners.
        # If they disagree, the seeded candidates would land on the wrong side.
        winners = {str(w) for w in (data.get("expected_winners") or [])}
        if {str(k) for k in pos_keys} != winners:
            type_vs_winner_mismatch.append(str(pid))

        for k in pos_keys:
            entry = snippet_index.get(str(ideas[k])[:_SNIPPET_LEN])
            if entry is None:
                positives_missing.append(f"{pid}/{k}")
            elif not entry.get("candidates"):
                positives_matched += 1
                positives_empty += 1
            else:
                positives_matched += 1

    if missing_type:
        problems.append(f"{len(missing_type)} idea(s) lack a POSITIVE/NEGATIVE metadata "
                        f"'type' — rekey cannot identify the positives. e.g. {missing_type[:5]}")
    if type_vs_winner_mismatch:
        problems.append(f"{len(type_vs_winner_mismatch)} instance(s) where the POSITIVE key "
                        f"disagrees with expected_winners: {type_vs_winner_mismatch[:5]}")
    if positives_missing and not allow_positive_misses:
        problems.append(f"{len(positives_missing)} positive(s) not found in the source cache: "
                        f"{positives_missing[:5]}\n"
                        f"      They would be retrieved from scratch rather than recycled, so "
                        f"their candidates would NOT match the baseline's.\n"
                        f"      Pass --allow-positive-misses to accept that (fine when the "
                        f"source cache simply never covered them).")
    if collisions:
        problems.append(f"{len(collisions)} duplicate {_SNIPPET_LEN}-char snippet(s) in the "
                        f"source cache — rekey would silently pick one of them.")

    pointwise_covered = pointwise_missing = 0
    if pointwise_yaml is not None:
        pairwise_texts = {str(v).strip() for d in pairwise_yaml.values()
                          for v in (d.get("ideas") or {}).values()}
        for entry in pointwise_yaml.values():
            text = str(entry.get("idea", "")).strip()
            if text in pairwise_texts:
                pointwise_covered += 1
            else:
                pointwise_missing += 1
        if pointwise_missing:
            problems.append(f"{pointwise_missing} pointwise idea(s) have no counterpart in the "
                            f"pairwise dataset — flatten would leave them uncached.")

    to_retrieve = negatives + positives_empty + len(positives_missing)

    print(f"  instances                     : {n_instances}")
    print(f"  positives recycled from source: {positives_matched}"
          + (f" ({positives_empty} had 0 candidates → will be re-retrieved)" if positives_empty else ""))
    if positives_missing:
        print(f"  positives NOT in source cache : {len(positives_missing)} "
              f"({', '.join(positives_missing[:5])}) → retrieved fresh")
    print(f"  negatives to retrieve         : {negatives}")
    print(f"  → total retrievals            : {to_retrieve}")
    if pointwise_yaml is not None:
        print(f"  pointwise ideas derivable     : {pointwise_covered}"
              + (f" ({pointwise_missing} MISSING)" if pointwise_missing else " (no API calls)"))

    if problems:
        print()
        for p in problems:
            print(f"  ✗ {p}")
        die(f"preflight failed for '{label}'. Nothing was written.")

    return {"n_instances": n_instances, "to_retrieve": to_retrieve}


# ── Manifest / destination ownership ──────────────────────────────────────────

def manifest_fingerprint(cfg: dict, ds: dict) -> dict:
    return {
        "source_cache": ds["source_cache"],
        "pairwise": ds["pairwise"],
        "pointwise": ds.get("pointwise"),
        "retrieval": cfg["retrieval"],
    }


def claim_destination(dest: Path, fingerprint: dict, label: str) -> dict:
    """Create dest (recording ownership) or validate an existing manifest. Never clobbers."""
    manifest_path = dest / _MANIFEST_NAME

    if dest.exists():
        if not manifest_path.exists():
            die(f"destination for '{label}' already exists and was not created by this "
                f"script:\n      {rel(dest)}\n"
                f"      Refusing to write into it. Move it aside or pick another "
                f"output_root/label.")
        manifest = json.loads(manifest_path.read_text())
        if manifest.get("fingerprint") != fingerprint:
            die(f"destination for '{label}' was built from different inputs:\n"
                f"      {rel(manifest_path)}\n"
                f"      Refusing to mix runs. Pick another label or move the old "
                f"directory aside.")
        print(f"  resuming an earlier run in {rel(dest)}")
        return manifest

    dest.mkdir(parents=True)
    manifest = {
        "created": datetime.now().isoformat(timespec="seconds"),
        "created_by": "scripts/build_combined_retrieval.py",
        "label": label,
        "fingerprint": fingerprint,
        "steps_done": [],
    }
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


def record_step(dest: Path, manifest: dict, step: str) -> None:
    if step not in manifest["steps_done"]:
        manifest["steps_done"].append(step)
    manifest["updated"] = datetime.now().isoformat(timespec="seconds")
    (dest / _MANIFEST_NAME).write_text(json.dumps(manifest, indent=2) + "\n")


def assert_unowned_absent(path: Path, manifest: dict, step: str, label: str) -> None:
    """A pre-existing output we have no record of writing is a foreign artifact."""
    if path.exists() and step not in manifest["steps_done"]:
        die(f"'{label}': {rel(path)} exists but this script has no record of creating it. "
            f"Refusing to overwrite.")


# ── Subprocess ────────────────────────────────────────────────────────────────

def run(cmd: List[str], guard: SourceGuard, context: str) -> None:
    print(f"  $ {' '.join(rel(Path(c)) if str(c).startswith(str(_REPO_ROOT)) else str(c) for c in cmd)}")
    env = dict(os.environ)
    src_dir = str(_REPO_ROOT / "src")
    env["PYTHONPATH"] = f"{src_dir}{os.pathsep}{env['PYTHONPATH']}" if env.get("PYTHONPATH") else src_dir
    result = subprocess.run([str(c) for c in cmd], cwd=_REPO_ROOT, env=env)
    guard.verify(context)
    if result.returncode != 0:
        die(f"{context} exited with code {result.returncode}. "
            f"Partial output is kept so the next run can resume.")


# ── Per-dataset pipeline ──────────────────────────────────────────────────────

def build_dataset(cfg: dict, ds: dict, args, snippet_index, collisions, guard: SourceGuard) -> dict:
    label = ds["label"]
    pairwise_path = resolve(ds["pairwise"])
    pointwise_path = resolve(ds["pointwise"]) if ds.get("pointwise") else None
    dest = resolve(cfg["output_root"]) / label

    print(f"\n{'=' * 78}\n{label}\n{'=' * 78}")
    print(f"  pairwise  : {rel(pairwise_path)}")
    if pointwise_path:
        print(f"  pointwise : {rel(pointwise_path)}")
    print(f"  dest      : {rel(dest)}")

    pairwise_yaml = load_yaml(pairwise_path)
    pointwise_yaml = load_yaml(pointwise_path) if pointwise_path else None
    plan = preflight(label, pairwise_yaml, pointwise_yaml, snippet_index, collisions,
                     args.allow_positive_misses)

    if args.dry_run:
        print("  [dry-run] nothing written.")
        return {"label": label, "dest": dest, "plan": plan, "built": False}

    manifest = claim_destination(dest, manifest_fingerprint(cfg, ds), label)

    pw_dir = dest / "pairwise"
    pw_cache = pw_dir / "retrieval_cache.json"
    pw_dir.mkdir(exist_ok=True)

    # ── Step 1: seed the positives ────────────────────────────────────────────
    assert_unowned_absent(pw_cache, manifest, "rekey", label)
    if "rekey" in manifest["steps_done"]:
        print("  [1/3] seed positives — already done, skipping")
    else:
        print("  [1/3] seed positives (rekey_retrieval_cache.py)")
        run([sys.executable, _REKEY,
             "--old-cache", resolve(cfg["source_cache"]),
             "--new-yaml", pairwise_path,
             "--output", pw_cache], guard, f"{label}:rekey")
        record_step(dest, manifest, "rekey")

    # ── Step 2: retrieve the negatives ────────────────────────────────────────
    if args.skip_retrieve:
        print("  [2/3] retrieve negatives — skipped (--skip-retrieve)")
    else:
        retrieval_cfg = dict(cfg["retrieval"])
        retrieval_cfg["test_inputs"] = str(pairwise_path)
        retrieval_cfg["output_file"] = str(pw_cache)
        cfg_path = pw_dir / "retrieval_config.yaml"
        cfg_path.write_text(yaml.safe_dump(retrieval_cfg, sort_keys=False))

        print(f"  [2/3] retrieve negatives (~{plan['to_retrieve']} ideas)")
        run([sys.executable, _RETRIEVE, "--config", cfg_path], guard, f"{label}:retrieve")
        record_step(dest, manifest, "retrieve")

    # ── Step 3: derive the pointwise cache ────────────────────────────────────
    ptw_cache = None
    if pointwise_path is None:
        print("  [3/3] pointwise cache — no pointwise dataset configured, skipping")
    elif args.skip_retrieve:
        # The pairwise cache holds positives only; flattening it now would bake that
        # gap into the pointwise cache and mark the step done.
        print("  [3/3] pointwise cache — skipped, pairwise cache is not complete yet")
    else:
        ptw_dir = dest / "pointwise"
        ptw_cache = ptw_dir / "retrieval_cache.json"
        assert_unowned_absent(ptw_cache, manifest, "flatten", label)
        # Always re-derived from whatever step 3 just produced. A repair pass
        # (retry_failed_queries) adds candidates to the pairwise cache, and a pointwise
        # cache left over from before it would be silently stale. Costs no API calls.
        ptw_dir.mkdir(exist_ok=True)
        print("  [3/3] derive pointwise cache (flatten_retrieval_cache.py)")
        run([sys.executable, _FLATTEN,
             "--pw-yaml", pairwise_path,
             "--pw-cache", pw_cache,
             "--ptw-yaml", pointwise_path,
             "--out-cache", ptw_cache], guard, f"{label}:flatten")
        record_step(dest, manifest, "flatten")

    return {"label": label, "dest": dest, "plan": plan, "built": True,
            "pairwise_cache": pw_cache, "pointwise_cache": ptw_cache,
            "pairwise_yaml": ds["pairwise"], "pointwise_yaml": ds.get("pointwise")}


# ── Reporting ─────────────────────────────────────────────────────────────────

def coverage(cache_path: Path, dataset_yaml: Path) -> str:
    """Report cached/missing/empty over the dataset's ideas, for both cache shapes."""
    if not cache_path.exists():
        return "cache not built"
    cache = json.loads(cache_path.read_text())
    data = load_yaml(dataset_yaml)
    cached = missing = empty = 0
    for pid, entry in data.items():
        ideas = entry.get("ideas")
        if ideas:  # pairwise → cache[pid][idea_key]
            for k in ideas:
                e = (cache.get(str(pid)) or {}).get(str(k))
                if e is None:
                    missing += 1
                elif e.get("candidates"):
                    cached += 1
                else:
                    empty += 1
        else:      # pointwise → cache[pid]
            e = cache.get(str(pid))
            if e is None:
                missing += 1
            elif e.get("candidates"):
                cached += 1
            else:
                empty += 1
    flag = "OK " if not missing and not empty else "!! "
    return f"{flag}cached={cached} missing={missing} empty={empty}"


def print_snippet(results: List[dict]) -> None:
    print(f"\n{'=' * 78}\nablations.yaml — add under `ablations:` "
          f"(pick `group:` deliberately; this sits on two axes)\n{'=' * 78}")
    for r in results:
        if not r.get("built"):
            continue
        label = r["label"]
        print(f"""
  {label}_retrieval_pairwise_vanilla:
    description: "{label} + retrieval"
    before_description: "Baseline backbone is claude-sonnet-4-5; evaluator has no access to related work."
    group: retrieval
    tracks: [pairwise-vanilla-ai]
    suppress_instance_mismatch_warning: true
    sweep:
      test_inputs: "{r['pairwise_yaml']}"
      retrieve_related_work: true
      retrieval_cache_file: "{rel(r['pairwise_cache'])}\"""")
        if r.get("pointwise_cache"):
            print(f"""
  {label}_retrieval_pointwise_vanilla:
    description: "{label} + retrieval"
    before_description: "Baseline backbone is claude-sonnet-4-5; evaluator has no access to related work."
    group: retrieval
    tracks: [pointwise-vanilla-ai]
    suppress_instance_mismatch_warning: true
    sweep:
      test_inputs: "{r['pointwise_yaml']}"
      retrieve_related_work: true
      retrieval_cache_file: "{rel(r['pointwise_cache'])}\"""")


# ── Main ──────────────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Build retrieval caches for combined (alt-backbone + retrieval) ablations.",
        formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__)
    parser.add_argument("--config", default="scripts/build_combined_retrieval.yaml")
    parser.add_argument("--datasets", help="Comma-separated labels to build (default: all).")
    parser.add_argument("--dry-run", action="store_true",
                        help="Preflight and cost estimate only; writes nothing.")
    parser.add_argument("--skip-retrieve", action="store_true",
                        help="Seed the positives but don't call the retrieval API.")
    parser.add_argument("--allow-positive-misses", action="store_true",
                        help="Proceed when some positives are absent from the source cache; "
                             "they are retrieved fresh instead of recycled.")
    args = parser.parse_args()

    cfg = load_yaml(resolve(args.config))
    for key in ("source_cache", "output_root", "retrieval", "datasets"):
        if key not in cfg:
            die(f"config is missing '{key}': {args.config}")

    datasets = cfg["datasets"]
    if args.datasets:
        wanted = {d.strip() for d in args.datasets.split(",")}
        unknown = wanted - {d["label"] for d in datasets}
        if unknown:
            die(f"unknown dataset label(s): {sorted(unknown)}")
        datasets = [d for d in datasets if d["label"] in wanted]

    source_cache_path = resolve(cfg["source_cache"])
    sources = [source_cache_path]
    for ds in datasets:
        ds["source_cache"] = cfg["source_cache"]
        sources.append(resolve(ds["pairwise"]))
        if ds.get("pointwise"):
            sources.append(resolve(ds["pointwise"]))
    for p in sources:
        if not p.exists():
            die(f"source not found: {rel(p)}")
    guard = SourceGuard(sources)

    if not args.dry_run and not args.skip_retrieve and not os.getenv("SECRETS"):
        die("SECRETS is not set — retrieval would run without API keys. "
            "export SECRETS=$PWD/secrets.toml (or pass --dry-run).")

    print(f"source cache : {rel(source_cache_path)} (read-only)")
    print(f"output root  : {rel(resolve(cfg['output_root']))}")
    print(f"datasets     : {', '.join(d['label'] for d in datasets)}")
    print("indexing source cache ...")
    snippet_index, collisions = build_snippet_index(json.loads(source_cache_path.read_text()))
    print(f"  {len(snippet_index)} unique idea snippets")

    results = [build_dataset(cfg, ds, args, snippet_index, collisions, guard) for ds in datasets]
    guard.verify("the full run")

    if args.dry_run:
        total = sum(r["plan"]["to_retrieve"] for r in results)
        print(f"\n[dry-run] {total} idea(s) would be retrieved across "
              f"{len(results)} dataset(s). Nothing was written.")
        return

    print(f"\n{'=' * 78}\nCoverage\n{'=' * 78}")
    for r in results:
        if not r.get("built"):
            continue
        print(f"  {r['label']}")
        print(f"    pairwise : {coverage(r['pairwise_cache'], resolve(r['pairwise_yaml']))}")
        if r.get("pointwise_cache"):
            print(f"    pointwise: {coverage(r['pointwise_cache'], resolve(r['pointwise_yaml']))}")
        print(f"    reports  : {rel(r['dest'])}/*/cache_status.md")

    print_snippet(results)


if __name__ == "__main__":
    main()
